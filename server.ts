// Proactive Escalation Engine (MoTA SLA Guarantee)
// DEMO SIMULATION: 30 seconds represents 30 days of inactivity in "Submitted"
// =========================================================================
export function checkApplicationEscalation(): { escalatedCount: number } {
  let escalatedCount = 0;
  const now = Date.now();

  applications = applications.map((app) => {
    if (app.status === 'Submitted') {
      const elapsedSeconds = (now - app.submittedAt) / 1000;
      if (elapsedSeconds >= 30) {
        escalatedCount++;
        const grievanceNum = `GRV-MOTA-${Math.floor(10000 + Math.random() * 90000)}`;

        // Create auto grievance
        const newGrievance: GrievanceRecord = {
          id: `grv-auto-${Date.now()}`,
          grievanceNumber: grievanceNum,
          applicationNumber: app.applicationNumber,
          schemeName: app.schemeName,
          subject: `Automated Escalation: Institutional verification delay for ${app.schemeName}`,
          description: `Application #${app.applicationNumber} was submitted on ${app.formattedSubmittedDate}. Central MoTA SLA monitor detected 30+ days of inactivity without district action. A formal grievance has been automatically logged and assigned to the District Nodal Officer.`,
          assignedOfficer: 'Shri Manoj Tirkey, IAS',
          officeDesignation: 'District Nodal Officer (Tribal Welfare), Ranchi',
          district: 'Ranchi',
          state: 'Jharkhand',
          status: 'Created',
          createdAt: 'Just now (Auto-Generated by MoTA SLA Monitor)',
          priority: 'High',
          timeline: [
            {
              stage: 'Delay Detected by MoTA SLA System',
              date: 'Just now',
              detail: 'Exceeded 30-day institutional verification SLA threshold',
              active: true
            },
            {
              stage: 'Grievance Auto-Filed',
              date: 'Just now',
              detail: `Auto-assigned to District Nodal Officer under ticket #${grievanceNum}`,
              active: true
            },
            {
              stage: 'Expedited Verification Order',
              date: 'Pending',
              detail: 'Nodal officer scheduled to issue 48-hour compliance notice to Institute',
              active: false
            }
          ]
        };

        grievances.unshift(newGrievance);

        // Create notification
        const autoNotif: NotificationItem = {
          id: `notif-esc-${Date.now()}`,
          title: '🚨 Application Delayed & Auto-Escalated',
          message: `Your ${app.schemeName} (#${app.applicationNumber}) had no update for 30 days. We automatically raised Grievance #${grievanceNum} with the District Nodal Officer.`,
          type: 'escalation',
          timestamp: 'Just now',
          timeAgo: 'Just now',
          read: false,
          actionRoute: 'applications'
        };

        notifications.unshift(autoNotif);

        return {
          ...app,
          status: 'Escalated' as const,
          grievanceId: grievanceNum,
          grievanceSummary: `Auto-escalated to District Nodal Officer (Ticket #${grievanceNum}) due to institutional SLA delay.`,
          delayReason: 'Institutional verification exceeded 30 days SLA threshold.',
          lastUpdated: 'Just now (Escalated)',
          timeline: [
            {
              stage: 'Application Submitted',
              description: 'Submitted through MoTA Unified Portal',
              completed: true,
              timestamp: app.formattedSubmittedDate
            },
            {
              stage: 'Verification Pending',
              description: 'Pending institute & district nodal officer validation',
              completed: true,
              timestamp: 'SLA Window Lapsed'
            },
            {
              stage: 'Delay Detected',
              description: 'System identified verification stall exceeding 30 days',
              completed: true,
              timestamp: 'Just now',
              escalated: true
            },
            {
              stage: 'Grievance Auto-Filed',
              description: `Automated Grievance #${grievanceNum} filed with District Nodal Officer`,
              completed: true,
              timestamp: 'Just now',
              current: true,
              escalated: true
            }
          ]
        };
      }
    }
    return app;
  });

  return { escalatedCount };
}

