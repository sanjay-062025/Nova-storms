/**
 * Downloads a structured JSON snapshot for data portability.
 */
export function downloadOfflineSnapshotJson(snapshot: CachedOfflineSnapshot): void {
  const blob = new Blob([JSON.stringify(snapshot, null, 2)], {
    type: 'application/json'
  });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = `mota-offline-snapshot-${snapshot.studentProfile.studentId || 'st2026'}.json`;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}
