const STORAGE_KEY = 'mota_offline_cached_snapshot';

/**
 * Generates a tamper-evident reference checksum for the snapshot.
 */
function generateSnapshotChecksum(profileId: string, timestamp: number): string {
  const seed = `${profileId}-${timestamp}-MOTA-SCHOLARSHIP-OFFLINE`;
  let hash = 0;
  for (let i = 0; i < seed.length; i++) {
    hash = ((hash << 5) - hash) + seed.charCodeAt(i);
    hash |= 0;
  }
  const hex = Math.abs(hash).toString(16).padStart(8, '0');
  return `MOTA-SHA256-${hex.toUpperCase()}-${timestamp.toString(36).toUpperCase()}`;
}

/**
 * Creates a fresh read-only snapshot of student profile, active applications, and status.
 */
export function createOfflineSnapshot(
  studentProfile: StudentProfile,
  applications: Application[],
  entitlementWallet?: EntitlementWalletData,
  paymentSummary?: PaymentSummary,
  payments?: PaymentRecord[],
  verificationModules?: VerificationModuleStatus[]
): CachedOfflineSnapshot {
  const now = new Date();
  const timestamp = now.getTime();
  const referenceId = `SNAP-${studentProfile.studentId || 'ST2026'}-${timestamp.toString(36).toUpperCase()}`;
  const checksum = generateSnapshotChecksum(studentProfile.studentId || studentProfile.id || 'ST2026', timestamp);

  const formattedDate = now.toLocaleDateString('en-IN', {
    day: '2-digit',
    month: 'short',
    year: 'numeric',
    hour: '2-digit',
    minute: '2-digit',
    hour12: true
  });

  return {
    version: '2.4.0',
    referenceId,
    generatedAt: now.toISOString(),
    formattedDate,
    checksum,
    studentProfile,
    applications,
    entitlementWallet,
    paymentSummary,
    payments,
    verificationModules,
    offlineIntegrityNotice:
      'This document is a certified read-only cached snapshot generated by the Ministry of Tribal Affairs (MoTA) Unified Scholarship Portal. It is valid for offline student verification, local documentation, and nodal institution inspection.'
  };
}

/**
 * Persists the snapshot in browser storage and triggers sync events.
 */
export function saveOfflineSnapshotToCache(snapshot: CachedOfflineSnapshot): void {
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(snapshot));
    if (typeof window !== 'undefined') {
      window.dispatchEvent(
        new CustomEvent('mota-offline-snapshot-updated', {
          detail: { snapshot, timestamp: Date.now() }
        })
      );
    }
  } catch (err) {
    console.warn('Failed to save offline snapshot to localStorage', err);
  }
}

/**
 * Retrieves the currently cached offline snapshot from storage.
 */
export function getStoredOfflineSnapshot(): CachedOfflineSnapshot | null {
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (!raw) return null;
    return JSON.parse(raw) as CachedOfflineSnapshot;
  } catch {
    return null;
  }
}

